#include "codexion.h"

void	sleep_milliseconds(t_env *env, long long ms)
{
	long long	start;

	start = elapsed_ms(env);
	while (elapsed_ms(env) - start < ms)
	{
		if (simulation_stopped(env))
			return ;
		usleep(500);
	}
}
